const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright');
const BASE='http://127.0.0.1:4173';
async function checkWidth(page,label){
 const d=await page.evaluate(()=>({width:window.innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(d.scroll<=d.width+3,label+' horizontal scroll: '+JSON.stringify(d));
 console.log('✓ '+label+' '+d.width+'px');
}
(async()=>{
 fs.mkdirSync('screenshots',{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--disable-dev-shm-usage']});
 for(const config of [{name:'desktop',viewport:{width:1440,height:900}},{name:'mobile',viewport:{width:390,height:844},isMobile:true,hasTouch:true}]){
  const page=await browser.newPage(config);
  page.setDefaultTimeout(15000);
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
  page.on('pageerror',err=>console.log('Page error:',err.message));
  await page.goto(BASE+'/',{waitUntil:'domcontentloaded'});
  await page.locator('.area-tile').first().waitFor();
  assert.match(await page.locator('#hero-title').textContent(),/O que você quer estudar hoje/);
  assert.equal(await page.locator('input[type=search]').count(),1);
  assert.equal(await page.locator('.home-explore-decoration').count(),0);
  assert.equal(await page.locator('.home-explore .home-section-intro p').count(),0);
  assert.equal(await page.locator('.home-explore .browser-toolbar').count(),0);
  assert.equal(await page.locator('.home-explore .browser-shortcuts').count(),0);
  assert.equal(await page.locator('#explore-content .area-tile').count(),9);
  assert.equal(await page.locator('.discovery-preview').count(),0);
  assert.equal(await page.locator('.home-hero-art').count(),0);
  assert.equal(await page.locator('[data-preview]').count(),0);
  assert.equal(await page.locator('img.mat-logo-img').count(),2);
  assert.equal(await page.locator('.header-promise').count(),1);
  assert.equal(await page.locator('.header-promise-bar').count(),1);
  const promise=await page.locator(config.name==='mobile'?'.header-promise-bar':'.header-promise').innerText();
  assert.match(promise,/ensino médio e vestibulares/i,'Cabeçalho deixa claro o público');
  assert.match(promise,/gratuito/i,'Cabeçalho deixa claro que é gratuito');
  assert.equal(await page.locator('.home-hero-copy>p').textContent(),'Listas de Exercícios e Teoria grátis. Simples assim');
  assert.match(await page.title(),/MAT MAT MAT!/);
  assert.equal(await page.locator('a.nav-cta[href="/teste-seu-nivel/"]').count(),1);
  await checkWidth(page,config.name+' home');
  await page.screenshot({path:'screenshots/'+config.name+'-home.png',fullPage:true});
  await page.locator('#hero-search').fill('Bhaskara');
  await page.locator('#search-output a[href="/aulas/A17/"]').first().waitFor();
  await checkWidth(page,config.name+' pesquisa');
  await page.screenshot({path:'screenshots/'+config.name+'-search.png',fullPage:true});
  await page.locator('#clear-search').click();
  await page.locator('a.area-tile[href="/explorar/?area=funcoes"]').click();
  await page.locator('.tr-topic h3 a[href="/explorar/?area=funcoes&assunto=fu-quadratica"]').waitFor();
  assert.equal(await page.locator('.tr-route > .tr-stop').count(),6);
  assert.equal(await page.locator('input[type=search]').count(),0,'explorador sem busca duplicada');
  assert.equal(await page.locator('.explorer-search-link').count(),0,'Sem botão Pesquisar nas páginas de área');
  await checkWidth(page,config.name+' assuntos');
  await page.screenshot({path:'screenshots/'+config.name+'-subjects.png',fullPage:true});
  await page.locator('.tr-topic h3 a[href="/explorar/?area=funcoes&assunto=fu-quadratica"]').click();
  await page.locator('.tr-lesson').first().waitFor();
  assert.equal(await page.locator('.tr-lesson').count(),6);
  await checkWidth(page,config.name+' aulas do assunto');
  await page.screenshot({path:'screenshots/'+config.name+'-topic.png',fullPage:true});
  await page.locator('.tr-lesson h3 a[href="/aulas/A17/"]').click();
  await page.waitForURL('**/aulas/A17/');
  await page.locator('.aula-step').first().waitFor();
  assert.equal(await page.locator('.aula-step').count(),4);
  assert.equal(await page.locator('.aula-rail [data-rail]').count(),4);
  assert.equal(await page.locator('#btn-share').textContent(),'Compartilhar');
  assert.equal(await page.locator('#btn-share').getAttribute('aria-label'),'Compartilhe essa aula');
  assert.equal(await page.locator('.lesson-tools .lesson-tool').count(),3);
  assert.equal(await page.locator('.lesson-tools svg').count(),3);
  // A nova barra permanece na mesma linha também nos 390px do iPhone.
  const actionBounds=await page.locator('.lesson-tools .lesson-tool').evaluateAll(els=>els.map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height}}));
  assert.ok(actionBounds[0].x<actionBounds[1].x&&actionBounds[1].x<actionBounds[2].x,'Três ações na mesma linha');
  assert.ok(Math.max(...actionBounds.map(b=>b.y))-Math.min(...actionBounds.map(b=>b.y))<3,'Ações alinhadas');
  assert.ok(actionBounds.every(b=>b.h<85),'Ações mais compactas');
  await page.locator('#btn-done').click();
  assert.equal(await page.locator('#btn-done').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#btn-done .lesson-tool-label').textContent(),'Estudada');
  await page.locator('#btn-done').click();
  await page.locator('#btn-fav').click();
  assert.equal(await page.locator('#btn-fav').getAttribute('aria-pressed'),'true');
  await page.locator('#btn-fav').click();
  await page.evaluate(()=>Object.defineProperty(navigator,'share',{configurable:true,value:undefined}));
  await page.locator('#btn-share').click();
  await page.locator('#lesson-share-options').waitFor({state:'visible'});
  assert.match(await page.locator('#share-whatsapp').getAttribute('href'),/^https:\/\/wa\.me\/\?text=/);
  await page.locator('#share-close').click();
  assert.equal(await page.locator('#lesson-share-options').isVisible(),false);
  await page.evaluate(()=>{
    window.__lastSharePayload=null;
    Object.defineProperty(navigator,'share',{configurable:true,value:function(payload){window.__lastSharePayload=payload;return Promise.resolve()}});
  });
  await page.locator('#btn-share').click();
  const sharePayload=await page.evaluate(()=>window.__lastSharePayload);
  assert.equal(sharePayload.url,BASE+'/aulas/A17/');
  assert.match(sharePayload.title,/MAT MAT MAT!/);
  assert.match(sharePayload.text,/Olha essa aula de matemática/);

  // Roteiro: o atalho leva ao modo prova, que responde pelo teclado.
  await page.locator('[data-rail="prova"]').click();
  await page.locator('#prova-start').click();
  await page.locator('#prova-root .aula-prova-q').waitFor();
  await page.waitForTimeout(400);
  await page.keyboard.press('a');
  await page.locator('#prova-next').waitFor();
  assert.equal(await page.locator('#prova-root .aula-opt.is-right').count(),1);
  assert.ok(await page.locator('.aula-rail').isVisible(),'Roteiro fixo visível durante a prova');
  await page.locator('#ex-list .aula-ex-ver').first().click();
  assert.ok(await page.locator('#ex-list .aula-ex-sol').first().isVisible());
  await checkWidth(page,config.name+' aula');
  await page.screenshot({path:'screenshots/'+config.name+'-lesson.png',fullPage:true});
  await page.goto(BASE+'/teste-seu-nivel/',{waitUntil:'domcontentloaded'});
  await page.locator('.diag-track-card').first().waitFor();
  assert.equal(await page.locator('.diag-track-card').count(),5);
  assert.equal(await page.locator('.header-promise-bar').count(),1);
  await checkWidth(page,config.name+' seleção de percurso');
  await page.screenshot({path:'screenshots/'+config.name+'-diagnostic.png',fullPage:true});
  await page.locator('[data-track="enem"]').click();
  assert.equal(await page.locator('.diag-skill-list>div').count(),4);
  await checkWidth(page,config.name+' apresentação da prova');
  await page.screenshot({path:'screenshots/'+config.name+'-diagnostic-intro.png',fullPage:true});
  await page.locator('#diag-begin').click();
  assert.equal(await page.locator('.diagnosis-option').count(),4);
  await checkWidth(page,config.name+' questão');
  await page.screenshot({path:'screenshots/'+config.name+'-diagnostic-question.png',fullPage:true});
  for(let i=0;i<12;i++){
   await page.locator('[data-diagnosis-answer="1"]').click();
   await page.locator('#diagnosis-next').click();
  }
  await page.locator('.diag-score-main').waitFor();
  assert.equal(await page.locator('.diagnosis-domain').count(),4);
  assert.equal(await page.locator('.diag-complexity>div').count(),3);
  assert.equal(await page.locator('.diag-review-item').count(),12);
  await checkWidth(page,config.name+' relatório diagnóstico');
  await page.screenshot({path:'screenshots/'+config.name+'-diagnostic-result.png',fullPage:true});
  // Busca: Enter abre a melhor aula direto.
  await page.goto(BASE+'/',{waitUntil:'domcontentloaded'});
  await page.locator('.area-tile').first().waitFor();
  await page.locator('#hero-search').fill('função modular');
  await page.locator('#quick-hits .hq-row.is-best').waitFor();
  assert.match(await page.locator('#quick-hits .hq-row.is-best').getAttribute('href'),/\/aulas\/A22\/$/);
  await checkWidth(page,config.name+' sugestões da busca');
  await page.locator('#hero-search').press('Enter');
  await page.waitForURL('**/aulas/A22/');
  await page.close();
 }
 await browser.close();
 console.log('✓ Browser: home, busca, catálogo e diagnóstico em desktop e celular');
})().catch(e=>{console.error(e);process.exit(1)});
